// Stamps business.json into the site and the worker.
//   site-src/**  ->  docs/**   (GitHub Pages serves docs/ from main)
//   business.json -> worker/src/business.js
// Tokens in pages: {{name}}, {{email}}, ... any top-level string in business.json,
// plus {{programs}}, {{program_options}}, {{year}}, {{json_ld}}, {{instagram_url}}, {{contact_line}}.
// Run: node scripts/build.mjs        Check only: node scripts/build.mjs --check
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, copyFileSync, existsSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const B = JSON.parse(readFileSync(join(root, "business.json"), "utf8"));
const check = process.argv.includes("--check");
let stale = [];

const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const dollars = (c) => "$" + (c / 100).toLocaleString("en-US", { maximumFractionDigits: 0 });

const programs = B.programs.map((p) => `
      <article class="program" id="program-${esc(p.key)}">
        <div class="program-head">
          <h3>${esc(p.name)}</h3>
          <p class="program-meta">${esc(p.length)}<span class="price">${dollars(p.price_cents)}${p.plan ? ` or ${p.plan.payments} monthly payments of ${dollars(p.plan.payment_cents)}` : ""}</span></p>
        </div>
        <p>${esc(p.blurb)}</p>
        <div class="buy">
          <button type="button" class="btn btn-quiet" data-buy="${esc(p.key)}" aria-label="Pay in full and enroll in ${esc(p.name)}">${p.plan ? "Pay in full" : "Pay and enroll"}</button>${p.plan ? `
          <button type="button" class="btn btn-quiet" data-buy="${esc(p.key)}" data-plan="1" aria-label="Enroll in ${esc(p.name)} with ${p.plan.payments} monthly payments">Pay monthly</button>` : ""}
        </div>
      </article>`).join("");

const program_options = B.programs.map((p) => `<option value="${esc(p.name)}">${esc(p.name)}</option>`).join("");

const json_ld = JSON.stringify({
  "@context": "https://schema.org",
  "@type": "HealthAndBeautyBusiness",
  name: B.name,
  description: B.tagline,
  url: B.site_url,
  email: B.email,
  ...(B.phone ? { telephone: B.phone } : {}),
  areaServed: B.location,
  sameAs: [B.instagram && `https://www.instagram.com/${B.instagram}/`, B.facebook].filter(Boolean),
  makesOffer: B.programs.map((p) => ({ "@type": "Offer", name: p.name, price: (p.price_cents / 100).toFixed(2), priceCurrency: "USD" })),
}).replace(/</g, "\\u003c");

const tokens = {
  ...Object.fromEntries(Object.entries(B).filter(([, v]) => typeof v === "string" || typeof v === "number").map(([k, v]) => [k, esc(v)])),
  programs,
  program_options,
  json_ld,
  year: String(new Date().getFullYear()),
  instagram_url: B.instagram ? `https://www.instagram.com/${esc(B.instagram)}/` : "",
  contact_line: [B.email && `<a href="mailto:${esc(B.email)}">${esc(B.email)}</a>`, B.phone && `<a href="tel:${esc(B.phone)}">${esc(B.phone)}</a>`, B.instagram && `<a href="https://www.instagram.com/${esc(B.instagram)}/">Instagram @${esc(B.instagram)}</a>`, B.facebook && `<a href="${esc(B.facebook)}">Facebook</a>`].filter(Boolean).join("<br>"),
  owner_line: B.owner_name ? `${esc(B.owner_name)}, ${esc(B.owner_title)}` : esc(B.owner_title),
};

function stamp(text, file) {
  return text.replace(/\{\{(\w+)\}\}/g, (m, k) => {
    if (!(k in tokens)) throw new Error(`Unknown token {{${k}}} in ${file}`);
    return tokens[k];
  });
}

function out(path, content) {
  const prev = existsSync(path) ? readFileSync(path) : null;
  const next = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (prev && prev.equals(next)) return;
  if (check) { stale.push(relative(root, path)); return; }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, next);
}

function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    const dest = join(root, "docs", relative(join(root, "site-src"), p));
    if (/\.(html|xml|txt|js|css|svg|webmanifest)$/.test(name)) out(dest, stamp(readFileSync(p, "utf8"), relative(root, p)));
    else out(dest, readFileSync(p));
  }
}

walk(join(root, "site-src"));
out(join(root, "worker/src/business.js"),
  "// Generated by scripts/build.mjs from business.json. Edit business.json, not this file.\nexport const BUSINESS = " + JSON.stringify(B, null, 2) + ";\n");

if (check && stale.length) { console.error("Out of date, run node scripts/build.mjs:\n  " + stale.join("\n  ")); process.exit(1); }
console.log(check ? "Build output is current." : "Built docs/ and worker/src/business.js");
